#!/usr/bin/env python3
"""Generate the SysML v2 projection of the neutral ``EntityState``.

One schema, many projections: :class:`pysos_interop.model.EntityState` is the
source of truth and ``sysml/entity_state.sysml`` is generated output.  Never
edit the generated file by hand; rerun::

    python tools/generate_sysml.py [OUTPUT]

The projection is a flat ``port def`` because this dialect has no struct or
record type, and a typed attribute on a port collapses to a single ``Real``.
Vectors become fixed-length ``Real[3]`` arrays, and only bare primitive type
names are used: qualified ``ScalarValues::*`` silently degrades to ``Real``.
"""

from __future__ import annotations

import inspect
import json
import sys
from dataclasses import MISSING, fields
from pathlib import Path
from typing import get_args, get_origin, get_type_hints

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src"
if str(SRC) not in sys.path:
    sys.path.insert(0, str(SRC))

from pysos_interop.model import EntityState  # noqa: E402

DEFAULT_OUTPUT = ROOT / "sysml" / "entity_state.sysml"

# Identity and run facts are forbidden in a model definition; the remaining
# names are static configuration and belong in parameters, not on a port.
EXCLUDED = frozenset(
    {
        "key",
        "timestamp",
        "exercise_id",
        "acceleration",
        "is_frozen",
        "entity_type",
        "platform_kind",
        "algorithm",
        "parameters",
    }
)

# Presentation-only annotation.  It is a comment, never a port member.
TRAILING_COMMENTS = {"orientation_rps": "(roll, pitch, yaw)"}

_PRIMITIVES = {bool: "Boolean", int: "Integer", float: "Real", str: "String"}


def _primitive(annotation: object, name: str) -> str:
    """Bare SysML primitive for a Python annotation, or fail loudly."""
    try:
        return _PRIMITIVES[annotation]
    except KeyError:
        raise TypeError(
            f"EntityState.{name}: no SysML primitive for {annotation!r}"
        ) from None


def _type_and_multiplicity(annotation: object, name: str) -> tuple[str, str | None]:
    """Map a Python annotation to ``(primitive, multiplicity)``."""
    if get_origin(annotation) is tuple:
        items = get_args(annotation)
        if not items or items[-1] is Ellipsis:
            raise TypeError(f"EntityState.{name}: only fixed-length tuples are projected")
        primitives = {_primitive(item, name) for item in items}
        if len(primitives) != 1:
            raise TypeError(f"EntityState.{name}: tuple elements must share one primitive")
        return primitives.pop(), str(len(items))
    return _primitive(annotation, name), None


def _literal(value: object) -> str:
    """SysML literal for a dataclass default value."""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, str):
        return json.dumps(value)
    return repr(value)


def projection() -> list[tuple[str, str, str | None, str | None, str | None]]:
    """Projected members in declaration order.

    Each item is ``(name, primitive, multiplicity, default, trailing_comment)``.
    """
    hints = get_type_hints(EntityState)
    members = []
    for field in fields(EntityState):
        if field.name in EXCLUDED:
            continue
        primitive, multiplicity = _type_and_multiplicity(hints[field.name], field.name)
        default = None if field.default is MISSING else _literal(field.default)
        members.append(
            (
                field.name,
                primitive,
                multiplicity,
                default,
                TRAILING_COMMENTS.get(field.name),
            )
        )
    return members


def render() -> str:
    """Render the whole ``.sysml`` file with ``\\n`` endings and one final newline."""
    doc = (inspect.getdoc(EntityState) or "").strip().splitlines()[0]
    members = projection()
    width = max(len(member[0]) for member in members)

    lines = [
        "// Generated by tools/generate_sysml.py from pysos_interop.model.EntityState.",
        "// Reproduce with: python tools/generate_sysml.py",
        "// Do not edit by hand: this file is generated output.",
        "",
        "package PysosEntity {",
        f"    /** {doc} */",
        "",
        "    port def EntityState {",
    ]
    for name, primitive, multiplicity, default, comment in members:
        declaration = f"        attribute {name:<{width}} : {primitive}"
        if multiplicity is not None:
            declaration += f"[{multiplicity}]"
        if default is not None:
            declaration += f" = {default}"
        declaration += ";"
        if comment is not None:
            declaration += f" // {comment}"
        lines.append(declaration)
    lines.extend(
        [
            "    }",
            "",
            "    part def Entity {",
            "        out port entityState : EntityState;",
            "    }",
            "}",
        ]
    )
    return "\n".join(lines) + "\n"


def write(path: Path = DEFAULT_OUTPUT) -> Path:
    """Write the projection to *path*."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(render())
    return path


def main(argv: list[str] | None = None) -> int:
    """Script entry point; an optional argument overrides the output path."""
    args = sys.argv[1:] if argv is None else list(argv)
    target = Path(args[0]) if args else DEFAULT_OUTPUT
    print(write(target))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
